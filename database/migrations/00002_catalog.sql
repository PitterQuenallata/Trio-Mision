-- Catálogo editorial: estilos, artistas, álbumes, canciones, temas y enlaces
-- externos (modelo-datos-v2.md §2.3).

-- +goose Up
create table styles (
  id         smallint primary key generated by default as identity,
  slug       text     not null unique,
  name       text     not null unique,
  sort_order smallint not null default 0
);

create table artists (
  id            uuid        primary key default gen_random_uuid(),
  slug          text        not null unique,
  name          text        not null,
  style_id      smallint    references styles (id) on delete set null,
  country       text,
  bio           text,
  cover_key     text,
  social_links  jsonb       not null default '{}',
  is_published  boolean     not null default false,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  deleted_at    timestamptz
);

create trigger artists_set_updated_at
  before update on artists
  for each row execute function set_updated_at();

create table artist_members (
  artist_id   uuid        not null references artists (id) on delete cascade,
  user_id     uuid        not null references profiles (id) on delete cascade,
  member_role text        not null check (member_role in ('member', 'manager')),
  created_at  timestamptz not null default now(),
  primary key (artist_id, user_id)
);

create table albums (
  id           uuid        primary key default gen_random_uuid(),
  artist_id    uuid        not null references artists (id) on delete cascade,
  title        text        not null,
  year         smallint,
  cover_key    text,
  sort_order   smallint    not null default 0,
  is_published boolean     not null default false,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  deleted_at   timestamptz
);

create trigger albums_set_updated_at
  before update on albums
  for each row execute function set_updated_at();

create table songs (
  id                 uuid        primary key default gen_random_uuid(),
  album_id           uuid        not null references albums (id) on delete cascade,
  title              text        not null,
  chordpro           text        not null,
  original_key       text,
  capo               smallint,
  bpm                smallint,
  author             text,
  arranger           text,
  publication_access text        not null default 'free'
                     check (publication_access in ('free', 'premium', 'purchase', 'creator')),
  tab_pdf_key        text,
  sort_order         smallint    not null default 0,
  is_published       boolean     not null default false,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  deleted_at         timestamptz
);

create trigger songs_set_updated_at
  before update on songs
  for each row execute function set_updated_at();

create table themes (
  id   smallint primary key generated by default as identity,
  slug text     not null unique,
  name text     not null unique
);

create table song_themes (
  song_id  uuid     not null references songs (id) on delete cascade,
  theme_id smallint not null references themes (id) on delete cascade,
  primary key (song_id, theme_id)
);

create table song_external_links (
  id                  uuid        primary key default gen_random_uuid(),
  song_id             uuid        not null references songs (id) on delete cascade,
  provider            text        not null check (provider in ('spotify', 'youtube')),
  external_id         text,
  canonical_url       text        not null,
  verified_at         timestamptz,
  availability_status text        not null default 'unknown'
                      check (availability_status in ('unknown', 'available', 'unavailable')),
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now(),
  unique (song_id, provider)
);

create trigger song_external_links_set_updated_at
  before update on song_external_links
  for each row execute function set_updated_at();

-- Índices: FKs, lecturas publicadas y sync por updated_at.
create index artists_published_idx on artists (name)
  where is_published and deleted_at is null;
create index artist_members_user_idx on artist_members (user_id);
create index albums_artist_idx on albums (artist_id);
create index albums_published_idx on albums (artist_id, sort_order)
  where is_published and deleted_at is null;
create index songs_album_idx on songs (album_id);
create index songs_published_idx on songs (album_id, sort_order)
  where is_published and deleted_at is null;
create index songs_updated_idx on songs (updated_at) where deleted_at is null;
create index song_themes_theme_idx on song_themes (theme_id);

